-- Final exam schema: roles, profiles, categories, products, orders, order_items.
-- Run in Supabase > SQL Editor. Safe to re-run (creates only what is missing).
-- The old `items` table is left untouched; its rows are copied into `products`.

begin;

-- 1. roles
create table if not exists public.roles (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  role        varchar not null unique,
  encoded_by  uuid references auth.users(id) on delete set null
);
insert into public.roles (role) values ('admin'), ('customer')
on conflict (role) do nothing;

-- 2. profiles (one row per auth user)
create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  created_at  timestamptz not null default now(),
  email       text,
  firstname   text,
  lastname    text,
  role_id     bigint references public.roles(id)
);

-- 3. categories
create table if not exists public.categories (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  name        text not null unique
);
insert into public.categories (name) values ('Uncategorized')
on conflict (name) do nothing;

-- 4. products
create table if not exists public.products (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  name         text not null,
  description  text,
  stock        smallint not null default 0 check (stock >= 0),
  image_url    text,
  category_id  bigint not null references public.categories(id),
  price        real not null default 0 check (price >= 0)
);

-- copy existing items into products (only if products is still empty)
insert into public.products (created_at, name, description, image_url, price, stock, category_id)
select i.created_at,
       coalesce(nullif(trim(i.name), ''), 'Unnamed'),
       i.description,
       i.image_url,
       greatest(coalesce(i.price, 0), 0),
       10,
       (select id from public.categories where name = 'Uncategorized')
from public.items i
where not exists (select 1 from public.products);

-- 5. orders
create table if not exists public.orders (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  user_id     uuid not null default auth.uid()
              references public.profiles(id) on delete cascade,
  status      text not null default 'pending',
  total       numeric(12,2) not null default 0 check (total >= 0)
);

-- 6. order_items (snapshot of name + unit price paid)
create table if not exists public.order_items (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  order_id      bigint not null references public.orders(id) on delete cascade,
  product_id    bigint references public.products(id) on delete set null,
  product_name  text not null,
  unit_price    numeric(12,2) not null check (unit_price >= 0),
  quantity      bigint not null check (quantity > 0)
);

create index if not exists products_category_id_idx on public.products(category_id);
create index if not exists orders_user_id_idx        on public.orders(user_id);
create index if not exists order_items_order_id_idx  on public.order_items(order_id);

commit;
